"""Optional Soup diagnostics (https://github.com/MakazhanAlpamys/Soup), run as an external CLI next to the custom engine.

Soup never trains, generates or merges here: these wrappers feed it our own artifacts and record exactly what it says.
Each call keeps the raw argv, exit code, stdout/stderr and any JSON report Soup wrote, under an evidence directory
(default runs/_soup/<UTC>/). A check that could not run is recorded as UNAVAILABLE / NOT RUN, never as passed.

Interfaces used (verified against soup_cli 0.77.2 --help and source; exit codes as documented there):
  soup data doctor <jsonl> --model <tokenizer> --max-length N -o report.json   chat template / EOS / BOS / truncation
  soup reward stress <verifier.py> --references refs.jsonl --output-report r.json   0 robust / 2 gameable
      the verifier is a .py with reward_fn(completions, answer=[...]) -> [float]; it must live under the cwd
  soup adapters check <adapter_dir> --json                 trained-or-not audit (zero B, Frobenius delta, keys)
  soup doctor                                              Soup's own interpreter: GPU, dependencies
  soup ship --evidence ev.json -o verdict.json             0 SHIP / 2 DON'T SHIP / 3 usage error
The Soup executable: --soup-bin, else $SOUP_BIN, else `soup` on PATH. Soup's audit log and telemetry are disabled for
these calls (SOUP_NO_AUDIT_LOG=1, --no-telemetry); Hugging Face access is offline (HF_HUB_OFFLINE=1) unless allowed.

What these checks do NOT cover is documented with the silent-failure registry (docs/silent_failures.md): data doctor
renders Soup's own SFT masks, not our GRPO completion masks; adapters check sees tensors, not policy behaviour; ship
compares two numbers without a confidence interval or a negative control.
"""
import json
import os
import shutil
import subprocess
import sys
import time
from datetime import datetime, timezone
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
EVIDENCE = ROOT / "runs" / "_soup"
UNAVAILABLE, NOT_RUN = "UNAVAILABLE", "NOT RUN"

REWARD_ADAPTER = '''"""Soup reward-stress adapter around qwen_grpo.sentiment.reward (generated by qwen_grpo/integrations/soup.py).
The GRPO reward unchanged: 1.0 iff the completion is exactly one canonical label equal to the reference."""
import sys
from pathlib import Path

sys.path.insert(0, str(next(p for p in Path(__file__).resolve().parents if (p / "qwen_grpo" / "sentiment.py").exists())))
from qwen_grpo.sentiment import reward  # noqa: E402


def reward_fn(completions, answer=None, **kwargs):
    if answer is None:
        raise ValueError("this reward compares each completion with its reference label: pass --references")
    texts = [c[-1]["content"] if isinstance(c, list) else str(c) for c in completions]
    return [reward(t, a) for t, a in zip(texts, answer, strict=True)]
'''

# A deliberately gameable reward for the fault-injection control: a substring match accepts any text containing the
# label (it is NOT the training reward; it shows whether Soup's stress test detects a gameable verifier).
PERMISSIVE_ADAPTER = '''"""Fault injection (generated by qwen_grpo/integrations/soup.py): a substring-match reward that a policy can game.
NOT the training reward."""


def reward_fn(completions, answer=None, **kwargs):
    texts = [c[-1]["content"] if isinstance(c, list) else str(c) for c in completions]
    return [float(a.upper() in t.upper()) for t, a in zip(texts, answer, strict=True)]
'''


def find(explicit=None):
    for cand in (explicit, os.environ.get("SOUP_BIN"), shutil.which("soup")):
        if cand and Path(cand).exists():
            return str(Path(cand))
    return None


def version(soup):
    r = subprocess.run([soup, "--version"], capture_output=True, text=True, timeout=120)
    return r.stdout.strip().splitlines()[0] if r.returncode == 0 and r.stdout.strip() else None


def call(soup, args, out_dir, name, allow_network=False, timeout=1800):
    """Run one Soup command from the repository root; keep everything it printed and its exit code."""
    env = {**os.environ, "SOUP_NO_AUDIT_LOG": "1", **({} if allow_network else {"HF_HUB_OFFLINE": "1",
                                                                             "TRANSFORMERS_OFFLINE": "1"})}
    argv = [soup, "--no-telemetry", *args]
    t0 = time.time()
    try:
        r = subprocess.run(argv, cwd=ROOT, env=env, capture_output=True, text=True, timeout=timeout)
        code, stdout, stderr = r.returncode, r.stdout, r.stderr
    except subprocess.TimeoutExpired as e:
        code, stdout, stderr = None, e.stdout or "", f"timeout after {timeout}s"
    stdout, stderr = scrub(stdout), scrub(stderr)
    rec = {"name": name, "argv": [Path(argv[0]).name, *argv[1:]], "cwd": ".", "exit": code,
           "seconds": round(time.time() - t0, 2), "stdout": stdout[-20000:], "stderr": stderr[-20000:]}
    (out_dir / f"{name}.log").write_text(f"$ {' '.join(rec['argv'])}\nexit {code}\n--- stdout\n{stdout}\n--- stderr\n{stderr}")
    return rec


def scrub(text):
    """Local absolute paths out of recorded output (evidence is committed): repository -> <repo>, home -> ~."""
    return (text or "").replace(str(ROOT), "<repo>").replace(str(Path.home()), "~")


def rel(p):
    return str(Path(p).resolve().relative_to(ROOT))


def read_json(path):
    try:
        return json.loads(Path(path).read_text())
    except (OSError, ValueError):
        return None


# --- inputs in Soup's formats -------------------------------------------------------------------------------

def chat_rows(n=200, split="train"):
    """Our prompts as chat rows (user turn = the exact prompt text, assistant turn = the gold label). Soup renders
    them with the tokenizer's own template; ours adds the empty non-thinking block at generation time."""
    from qwen_grpo.sentiment import load_splits, prompt_text
    rows = load_splits()[split][:n]
    return [{"messages": [{"role": "user", "content": prompt_text(r["text"])},
                          {"role": "assistant", "content": r["label"]}]} for r in rows]


def write_jsonl(path, rows):
    path.write_text("".join(json.dumps(r) + "\n" for r in rows))
    return path


# --- checks ------------------------------------------------------------------------------------------------------

def data_doctor(soup, out_dir, model="Qwen/Qwen3-0.6B", n=200, max_length=256, rows=None, name="data_doctor"):
    data = write_jsonl(out_dir / f"{name}_input.jsonl", rows if rows is not None else chat_rows(n))
    report = out_dir / f"{name}.json"
    rec = call(soup, ["data", "doctor", rel(data), "--model", model, "--max-length", str(max_length),
                      "--sample", str(n), "-o", rel(report)], out_dir, name)
    return {**rec, "input": rel(data), "report": read_json(report)}


def reward_stress(soup, out_dir, n=200, permissive=False, name=None):
    from qwen_grpo.sentiment import load_splits
    name = name or ("reward_stress_permissive" if permissive else "reward_stress")
    verifier = out_dir / f"{name}_verifier.py"
    verifier.write_text(PERMISSIVE_ADAPTER if permissive else REWARD_ADAPTER)
    refs = write_jsonl(out_dir / f"{name}_references.jsonl",
                       [{"answer": r["label"]} for r in load_splits()["validation"][:n]])
    report = out_dir / f"{name}.json"
    rec = call(soup, ["reward", "stress", rel(verifier), "--references", rel(refs), "--output-report", rel(report)],
               out_dir, name)
    shutil.rmtree(out_dir / "__pycache__", ignore_errors=True)  # Soup imports the verifier in place
    verdict = {0: "robust", 2: "gameable"}.get(rec["exit"], "error")
    return {**rec, "verifier": rel(verifier), "permissive_fault": permissive, "verdict": verdict,
            "report": read_json(report)}


def adapter_check(soup, out_dir, adapter, name=None):
    name = name or "adapter_check_" + Path(adapter).name
    rec = call(soup, ["adapters", "check", rel(adapter), "--json"], out_dir, name)
    try:
        parsed = json.loads(rec["stdout"][rec["stdout"].index("{"):])
    except ValueError:
        parsed = None
    return {**rec, "adapter": rel(adapter), "report": parsed}


def doctor(soup, out_dir):
    rec = call(soup, ["doctor"], out_dir, "doctor")
    same = Path(sys.executable).resolve().parent == Path(soup).resolve().parent
    return {**rec, "same_interpreter_as_training": same,
            "note": None if same else "Soup runs in another interpreter: its doctor/env checks describe Soup's "
            "environment, not the training environment (install soup-cli into the training venv to use them there)"}


def ship_evidence(base_acc, tuned_acc, benchmarks=None):
    return {"task": {"mode": "metric", "base": float(base_acc), "tuned": float(tuned_acc)},
            "benchmarks": benchmarks or {}}


def ship(soup, out_dir, evidence, name="ship"):
    ev = out_dir / f"{name}_evidence.json"
    ev.write_text(json.dumps(evidence, indent=1))
    out = out_dir / f"{name}_verdict.json"
    rec = call(soup, ["ship", "--evidence", rel(ev), "-o", rel(out)], out_dir, name)
    verdict = {0: "SHIP", 2: "DON'T SHIP"}.get(rec["exit"], "error")
    return {**rec, "evidence": evidence, "verdict": verdict, "report": read_json(out)}


def ship_from_final_results(results, soup_bin=None):
    """Soup's offline ship on the held-out base vs trained accuracy of the final evaluation, beside our verdict."""
    soup = find(soup_bin)
    if soup is None:
        return {"status": UNAVAILABLE, "detail": "Soup CLI not found (--soup-bin, $SOUP_BIN or PATH)"}
    models = (results.get("held_out") or {}).get("models") or {}  # scripts/final_eval.py: {name: metrics}
    base, trained = (models.get(k, {}).get("accuracy") for k in ("base", "trained"))
    if base is None or trained is None:
        return {"status": NOT_RUN, "detail": "no held-out base/trained accuracy in research/l2l/final_results.json yet"}
    out_dir = new_dir()
    return ship(soup, out_dir, ship_evidence(base, trained))


def new_dir(base=None):
    d = Path(base) if base else EVIDENCE / datetime.now(timezone.utc).strftime("%Y%m%dT%H%M%SZ")
    d.mkdir(parents=True, exist_ok=True)
    return d


def render(rec):
    if "status" in rec:
        return f"soup: {rec['status']} ({rec['detail']})"
    return f"soup {rec['name']}: exit {rec['exit']}" + (f", verdict {rec['verdict']}" if "verdict" in rec else "")


# --- CLI ------------------------------------------------------------------------------------------------------------

CHECKS = ("doctor", "data-doctor", "reward-stress", "adapter-check", "ship-demo", "all")


def add_arguments(p):
    p.add_argument("check", choices=CHECKS)
    p.add_argument("--soup-bin", help="the Soup executable (default: $SOUP_BIN, then PATH)")
    p.add_argument("--evidence-dir", help="where to keep raw outputs (default runs/_soup/<UTC>/)")
    p.add_argument("--model", default="Qwen/Qwen3-0.6B", help="tokenizer for data-doctor (local cache)")
    p.add_argument("--adapter", action="append", default=[], help="adapter directory for adapter-check (repeatable)")
    p.add_argument("--n", type=int, default=200)


def run_checks(which, soup, out_dir, model="Qwen/Qwen3-0.6B", adapters=(), n=200):
    """The selected checks; 'all' = doctor, data doctor (+ a broken-template control), reward stress (strict reward
    and the permissive fault), adapter checks, and ship on two synthetic score pairs (behaviour probe)."""
    results = {"soup": Path(soup).name, "version": version(soup), "started_utc": datetime.now(timezone.utc).isoformat(
        timespec="seconds"), "evidence_dir": rel(out_dir), "checks": []}
    add = results["checks"].append
    if which in ("doctor", "all"):
        add(doctor(soup, out_dir))
    if which in ("data-doctor", "all"):
        add(data_doctor(soup, out_dir, model, n))
        # control: the assistant turn missing (nothing to train on) - does the doctor flag it?
        rows = [{"messages": r["messages"][:1]} for r in chat_rows(min(n, 50))]
        add(data_doctor(soup, out_dir, model, min(n, 50), rows=rows, name="data_doctor_fault_no_assistant"))
    if which in ("reward-stress", "all"):
        add(reward_stress(soup, out_dir, n))
        add(reward_stress(soup, out_dir, n, permissive=True))
    if which in ("adapter-check", "all"):
        for a in adapters:
            add(adapter_check(soup, out_dir, Path(a)))
    if which in ("ship-demo", "all"):
        # behaviour probe with the reference run's own numbers (runs/qwen, validation accuracy at step 90) and an
        # insignificant one-example improvement: Soup's offline ship has no CI, so the second also ships unless a
        # noise floor is supplied
        add(ship(soup, out_dir, ship_evidence(0.7486, 0.8096), name="ship_reference_run"))
        # with a synthetic, unchanged leg-2 benchmark (so only the task leg decides): a real gain, and a gain of one
        # example in 1066 that no confidence interval would call significant
        same = {"synthetic_unchanged": {"base": 0.5, "tuned": 0.5}}
        add(ship(soup, out_dir, ship_evidence(0.7486, 0.8096, same), name="ship_reference_run_synthetic_leg2"))
        add(ship(soup, out_dir, ship_evidence(0.7486, 0.7486 + 1 / 1066, same), name="ship_insignificant_gain"))
    (out_dir / "summary.json").write_text(json.dumps(results, indent=1))
    return results


def cli(a):
    soup = find(a.soup_bin)
    if soup is None:
        print("Soup CLI not found: pass --soup-bin, set $SOUP_BIN, or put `soup` on PATH. Nothing was checked "
              "(UNAVAILABLE, not passed).")
        return 2
    out_dir = new_dir(a.evidence_dir)
    adapters = a.adapter or (["runs/qwen/checkpoints/step0", "runs/qwen/checkpoints/step90"]
                             if a.check in ("adapter-check", "all") else [])
    res = run_checks(a.check, soup, out_dir, a.model, adapters, a.n)
    for r in res["checks"]:
        print(render(r))
    print(f"raw outputs: {rel(out_dir)}/ (summary.json)")
    return 0
