"""Incremental on-disk rollout records (Ticket 09): one file per rollout group, written once, crash-consistently.

RolloutStore(<dir>/rollouts, run_id) holds
  group_<id>.pt   torch.save of one record (tensors on the CPU), published by temp file + fsync + rename
  index.jsonl     one JSON line per published record (append + fsync after the record file is in place)
A record is everything a GRPO update of that group needs, and what identifies it:
  group_id (= the attempt number), run_id, policy_version (the number of committed optimizer steps of the policy that
  generated it), occurrences [(epoch, position, sample_id)], prompt ids / labels, input_ids, attention_mask,
  response_ids, completion_mask, prompt_len, rewards, advantages and old_logp (None for a zero-signal group),
  zero_signal, and the sha256 of its tensors.
read() refuses a record of another run, of another policy version than the caller expects, or whose tensors do not
match their recorded hash: records of incompatible policy versions are never mixed into an update.
Only the pending group's tensors are in memory during training; every earlier group lives only on disk.
discard_after(g) moves records of groups > g (generated after the last committed checkpoint, so uncommitted) to
orphaned/<stamp>/ and rewrites the index without them: a resumed run regenerates those groups.
"""
import hashlib
import json
import os
import shutil
import time
from pathlib import Path

import torch

from qwen_grpo.streaming.dataset import atomic_write_text, fsync_dir

TENSORS = ("input_ids", "attention_mask", "response_ids", "completion_mask", "rewards", "advantages", "old_logp")


def tensor_sha256(record):
    h = hashlib.sha256()
    for k in TENSORS:
        t = record.get(k)
        h.update(k.encode())
        if t is not None:
            h.update(str(t.dtype).encode() + str(tuple(t.shape)).encode())
            h.update(t.detach().cpu().contiguous().view(torch.uint8).numpy().tobytes())
    return h.hexdigest()


class RolloutStore:
    def __init__(self, directory, run_id):
        self.dir = Path(directory)
        self.dir.mkdir(parents=True, exist_ok=True)
        self.run_id = run_id

    def path(self, group_id):
        return self.dir / f"group_{group_id:06d}.pt"

    def index(self):
        p = self.dir / "index.jsonl"
        return [json.loads(line) for line in p.read_text().splitlines() if line.strip()] if p.exists() else []

    def write(self, record):
        """Publish one group's record (tensors moved to the CPU), then append its index line."""
        rec = {k: (v.detach().cpu() if isinstance(v, torch.Tensor) else v) for k, v in record.items()}
        rec["run_id"] = self.run_id
        rec["sha256"] = tensor_sha256(rec)
        g = rec["group_id"]
        final = self.path(g)
        if final.exists():
            raise RuntimeError(f"rollout group {g} is already on disk ({final}): a committed group is never regenerated")
        tmp = final.with_name(f".{final.name}.tmp-{os.getpid()}")
        with open(tmp, "wb") as f:
            torch.save(rec, f)
            f.flush()
            os.fsync(f.fileno())
        os.replace(tmp, final)
        fsync_dir(self.dir)
        line = {"group_id": g, "file": final.name, "sha256": rec["sha256"], "policy_version": rec["policy_version"],
                "zero_signal": rec["zero_signal"], "occurrences": rec["occurrences"], "run_id": self.run_id}
        with open(self.dir / "index.jsonl", "a") as f:
            f.write(json.dumps(line) + "\n")
            f.flush()
            os.fsync(f.fileno())
        return rec["sha256"]

    def read(self, group_id, policy_version, device="cpu"):
        rec = torch.load(self.path(group_id), weights_only=True)
        if rec["run_id"] != self.run_id:
            raise RuntimeError(f"rollout group {group_id} belongs to run {rec['run_id']}, not {self.run_id}")
        if rec["policy_version"] != policy_version:
            raise RuntimeError(f"rollout group {group_id} was generated by policy version {rec['policy_version']}, the "
                               f"checkpoint expects {policy_version}: refusing to mix policy versions")
        if tensor_sha256(rec) != rec["sha256"]:
            raise RuntimeError(f"rollout group {group_id}: tensors do not match their recorded sha256")
        return {k: (v.to(device) if isinstance(v, torch.Tensor) else v) for k, v in rec.items()}

    def discard_after(self, group_id):
        """Move records of groups > group_id (uncommitted) aside and drop them from the index. -> moved group ids."""
        later = sorted(int(p.stem.split("_")[1]) for p in self.dir.glob("group_*.pt") if int(p.stem.split("_")[1]) > group_id)
        for p in self.dir.glob(".group_*.tmp-*"):
            p.unlink()  # a record write that was interrupted before its rename
        if later:
            dest = self.dir / "orphaned" / time.strftime("%Y%m%dT%H%M%S")
            dest.mkdir(parents=True, exist_ok=True)
            for g in later:
                shutil.move(str(self.path(g)), dest / self.path(g).name)
        kept = [line for line in self.index() if line["group_id"] <= group_id]
        atomic_write_text(self.dir / "index.jsonl", "".join(json.dumps(line) + "\n" for line in kept))
        return later
